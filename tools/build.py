"""Build helper for Orbital Loom X.

One codebase, two builds:
  * web   : index.html as committed (GitHub Pages). Adds the on-screen settings
            panel, sound, export and the toolbar (props.js, settings.js, web.js).
  * desktop: release/Orbital_Loom_X_Galactic_Voyage.zip for Lively Wallpaper.
            Same engine, stories, eye and sound; no settings panel, export or
            fullscreen. Options live in Lively's own Customize panel.

Run from the repository root:  python tools/build.py
"""
import io
import json
import os
import re
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)

props = json.load(io.open('LivelyProperties.json', encoding='utf-8-sig'))
json.load(io.open('LivelyInfo.json', encoding='utf-8-sig'))  # validate

web_props = dict(props)
with io.open('props.js', 'w', encoding='utf-8', newline='\n') as f:
    f.write('// AUTO-GENERATED by tools/build.py from LivelyProperties.json, do not edit by hand.\n')
    f.write('window.LIVELY_PROPS = ')
    f.write(json.dumps(web_props, ensure_ascii=False, indent=1))
    f.write(';\n')

html = io.open('index.html', encoding='utf-8').read()
desk = re.sub(r'\s*<!-- web-only:start.*?web-only:end -->', '', html, flags=re.S)
assert 'settings.js' not in desk and 'web.js' in desk
# WebGL will not accept images loaded from file://, so the wallpaper carries the maps as data URIs
import base64
maps = {}
for fn in sorted(os.listdir('textures')):
    if fn.endswith('.jpg'):
        maps[fn[:-4]] = 'data:image/jpeg;base64,' + base64.b64encode(open(os.path.join('textures', fn), 'rb').read()).decode('ascii')
maps_js = '// AUTO-GENERATED by tools/build.py from textures/. Maps: Solar System Scope, CC BY 4.0.\nwindow.OLX_MAPS = ' + json.dumps(maps) + ';\n'
desk = desk.replace('<script src="script.js', '<script src="maps.js"></script>\n  <script src="script.js', 1)
# the wallpaper keeps the eye and sound buttons but not export / fullscreen
desk = desk.replace('<script src="web.js', '<script>window.OLX_DESKTOP = true;</script>\n  <script src="web.js', 1)

FILES = ['style.css', 'shaders.js', 'script.js', 'stories.js', 'web.js',
         'LivelyInfo.json', 'LivelyProperties.json', 'thumbnail.jpg', 'preview.gif',
         'README_AR.txt', 'LICENSE']
os.makedirs('release', exist_ok=True)
out = os.path.join('release', 'Orbital_Loom_X_Galactic_Voyage.zip')
with zipfile.ZipFile(out, 'w', zipfile.ZIP_DEFLATED, compresslevel=9) as z:
    z.writestr('index.html', desk)
    z.writestr('maps.js', maps_js)
    z.write(os.path.join('textures', 'CREDITS.txt'), 'textures/CREDITS.txt')
    for name in FILES:
        z.write(name, name)
print('props.js written;', out, os.path.getsize(out), 'bytes')
