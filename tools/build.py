"""Build helper for Orbital Loom X.

One codebase, two builds:
  * web   : index.html as committed (GitHub Pages). Adds the on-screen settings
            panel, sound, export and the toolbar (props.js, settings.js, web.js).
  * desktop: release/Orbital_Loom_X_Galactic_Voyage.zip for Lively Wallpaper.
            Same engine and stories, without the browser-only scripts; options
            live in Lively's own Customize panel.

Run from the repository root:  python tools/build.py
"""
import io
import json
import os
import re
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)

props = json.load(io.open('LivelyProperties.json', encoding='utf-8-sig'))
json.load(io.open('LivelyInfo.json', encoding='utf-8-sig'))  # validate

# options that only exist in the browser build
web_props = dict(props)
web_props['volume'] = {'type': 'slider', 'value': 70, 'min': 0, 'max': 100, 'step': 5,
                       'text': 'مستوى الصوت % / Sound volume %'}
with io.open('props.js', 'w', encoding='utf-8', newline='\n') as f:
    f.write('// AUTO-GENERATED by tools/build.py from LivelyProperties.json, do not edit by hand.\n')
    f.write('window.LIVELY_PROPS = ')
    f.write(json.dumps(web_props, ensure_ascii=False, indent=1))
    f.write(';\n')

html = io.open('index.html', encoding='utf-8').read()
desk = re.sub(r'\s*<!-- web-only:start.*?web-only:end -->', '', html, flags=re.S)
assert 'web.js' not in desk and 'settings.js' not in desk

FILES = ['style.css', 'shaders.js', 'script.js', 'stories.js',
         'LivelyInfo.json', 'LivelyProperties.json', 'thumbnail.jpg', 'preview.gif',
         'README_AR.txt', 'LICENSE']
os.makedirs('release', exist_ok=True)
out = os.path.join('release', 'Orbital_Loom_X_Galactic_Voyage.zip')
with zipfile.ZipFile(out, 'w', zipfile.ZIP_DEFLATED, compresslevel=9) as z:
    z.writestr('index.html', desk)
    for name in FILES:
        z.write(name, name)
print('props.js written;', out, os.path.getsize(out), 'bytes')
